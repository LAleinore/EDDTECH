  ru('ru', 'Русский'),
  kk('kk', 'Қазақша'),
  en('en', 'English');

  final String code;
  final String title;
  const AppLanguage(this.code, this.title);

  static AppLanguage fromCode(String code) {
    return AppLanguage.values.firstWhere(
      (lang) => lang.code == code,
      orElse: () => AppLanguage.ru,
    );
  }
